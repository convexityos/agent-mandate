/**
 * Spec §3.1 — the conformance vectors.
 *
 * A spec with an executable conformance suite is a standard. One without is a
 * document. These files let a third-party implementation claim `am/1-core`
 * without reading a line of this TypeScript.
 *
 * ## The rule that makes them worth anything
 *
 * **Every expectation here is written by hand from the specification.** Nothing
 * is recorded from what this implementation happens to do. That distinction is
 * the whole value: vectors generated by running the reference implementation and
 * capturing its output cannot disagree with it, so they encode its bugs as
 * conformance requirements and certify future implementations for reproducing
 * them.
 *
 * `test/vectors.test.ts` then runs every vector through this implementation and
 * asserts the hand-written verdict. When those disagree, exactly one of the two
 * is wrong and it is worth finding out which — which is the point.
 *
 * Three of the cases below were spec defects found by property tests rather than
 * by reading code, which makes them precisely the cases another implementation
 * gets wrong.
 */

/** Fixed so the emitted files are byte-identical run to run. */
export const VECTOR_NOW = 1800000000;
const LEDGER = 'https://ledger.example.com';

const seed = (n: number): Uint8Array => new Uint8Array(32).fill(n);

export const KEYS = {
  principal: agentKeyFromSeed(seed(1)),
  agentA: agentKeyFromSeed(seed(2)),
  agentB: agentKeyFromSeed(seed(3)),
  agentC: agentKeyFromSeed(seed(4)),
  stranger: agentKeyFromSeed(seed(5)),
} as const;

type KeyName = keyof typeof KEYS;

export interface LinkSpec {
  holder: KeyName;
  cav: Caveats;
  jti?: string;
  iat?: number;
  exp?: number;
  nbf?: number;
  /** Sign with this key instead of the previous holder — for forgery cases. */
  signedBy?: KeyName;
  /** Mutate claims after construction, for deliberately invalid chains. */
  tamper?: (c: Record<string, unknown>) => void;
  /** Replace the finished token entirely, for signature-level attacks. */
  rewrite?: (token: string) => string;
}

export interface ChainVector {
  id: string;
  spec: string;
  title: string;
  why: string;
  tokens: string[];
  request: Record<string, unknown>;
  now: number;
  trustedRootIssuers: string[];
  presenterJkt?: string;
  maxDepth?: number;
  expect: { ok: true; effective?: Caveats } | { ok: false; code: string };
}

function buildChain(links: LinkSpec[]): string[] {
  const tokens: string[] = [];
  let parentJti: string | null = null;
  let signer: AgentKey = KEYS.principal;

  links.forEach((l, i) => {
    const jti = l.jti ?? `mnd_${i}`;
    const claims: Record<string, unknown> = {
      v: 'am/1',
      typ: 'mandate',
      jti,
      iss: (l.signedBy !== undefined ? KEYS[l.signedBy] : signer).did,
      sub: KEYS[l.holder].did,
      par: parentJti,
      iat: l.iat ?? VECTOR_NOW - 60,
      nbf: l.nbf ?? l.iat ?? VECTOR_NOW - 60,
      exp: l.exp ?? VECTOR_NOW + 3600,
      cnf: { jkt: KEYS[l.holder].jkt },
      ledger: LEDGER,
      cav: l.cav,
    };
    l.tamper?.(claims);
    const actualSigner = l.signedBy !== undefined ? KEYS[l.signedBy] : signer;
    let token = signMandate(claims as unknown as MandateClaims, actualSigner, actualSigner.did);
    if (l.rewrite !== undefined) token = l.rewrite(token);
    tokens.push(token);
    parentJti = jti;
    signer = KEYS[l.holder];
  });
  return tokens;
}

