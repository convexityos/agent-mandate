export interface VectorFiles {
  'index.json': unknown;
  'keys.json': unknown;
  'chain.json': unknown;
  'caveats.json': unknown;
  'uri.json': unknown;
}

export function buildVectors(): VectorFiles {
  const chain: ChainVector[] = CHAIN_CASES.map((c) => ({
    id: c.id,
    spec: c.spec,
    title: c.title,
    why: c.why,
    tokens: buildChain(c.links),
    request: c.request,
    now: c.now ?? VECTOR_NOW,
    trustedRootIssuers: c.trustedRootIssuers ?? [KEYS.principal.did],
    ...(c.presenterJkt !== undefined ? { presenterJkt: c.presenterJkt } : {}),
    ...(c.maxDepth !== undefined ? { maxDepth: c.maxDepth } : {}),
    expect: c.expect,
  }));

  return {
    'index.json': {
      version: 'am/1',
      suites: [
        { file: 'chain.json', kind: 'chain', count: chain.length },
        { file: 'caveats.json', kind: 'caveats', count: CAVEAT_VECTORS.length },
        { file: 'uri.json', kind: 'uri', count: URI_VECTORS.length },
      ],
      keys: 'keys.json',
      now: VECTOR_NOW,
    },
    'keys.json': {
      note:
        'Test keys, published deliberately. Each seed is a 32-byte Ed25519 seed as ' +
        'defined by RFC 8032 §5.1.5 — derive the public key from it and you should get ' +
        'the did and jkt below. Never use these for anything.',
      keys: Object.entries(KEYS).map(([name, k]) => ({
        name,
        seedHex: Buffer.from(new Uint8Array(32).fill(nameToSeed(name))).toString('hex'),
        did: k.did,
        jwk: k.jwk,
        jkt: k.jkt,
      })),
    },
    'chain.json': { vectors: chain },
    'caveats.json': { vectors: CAVEAT_VECTORS },
    'uri.json': { vectors: URI_VECTORS },
  };
}

function nameToSeed(name: string): number {
  const order: KeyName[] = ['principal', 'agentA', 'agentB', 'agentC', 'stranger'];
  return order.indexOf(name as KeyName) + 1;
}
